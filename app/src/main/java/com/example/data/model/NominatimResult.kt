package com.example.data.model

import com.example.data.model.PlaceCategory

data class NominatimResult(
    val place_id: Long = 0,
    val display_name: String = "",
    val lat: String = "0.0",
    val lon: String = "0.0",
    val type: String = "",
    val category: String = "",
    val placeName: String? = null,
    val road: String? = null,
    val houseNumber: String? = null,
    val suburb: String? = null,
    val city: String? = null,
    val postcode: String? = null,
    val openingHours: String? = null,
    val wheelchair: String? = null,
    val brand: String? = null,
    val operator: String? = null,
    val phone: String? = null,
    val email: String? = null,
    val website: String? = null,
    val wikipedia: String? = null,
    val wikidata: String? = null,
    val fee: String? = null,
    val charge: String? = null,
    val startDate: String? = null,
    val historicType: String? = null,
    val colorHex: String? = null,
    val showOnMap: Boolean = true,
    val placeCategory: PlaceCategory = PlaceCategory.GENERAL,
    val displayName: String = display_name,
    val isLocalStop: Boolean = false,
    val stopId: String? = null,
    val stopType: String? = null
) {
    val latitude: Double get() = lat.toDoubleOrNull() ?: 0.0
    val longitude: Double get() = lon.toDoubleOrNull() ?: 0.0

    constructor(
        displayName: String,
        latitude: Double,
        longitude: Double,
        type: String = "",
        category: String = "",
        isLocalStop: Boolean = false,
        stopId: String? = null,
        stopType: String? = null,
        placeCategory: PlaceCategory = PlaceCategory.GENERAL,
        placeName: String? = displayName.split(",").firstOrNull()?.trim() ?: displayName,
        road: String? = null,
        houseNumber: String? = null,
        suburb: String? = null,
        city: String? = null,
        postcode: String? = null,
        openingHours: String? = null,
        wheelchair: String? = null,
        brand: String? = null,
        operator: String? = null,
        phone: String? = null,
        email: String? = null,
        website: String? = null,
        wikipedia: String? = null,
        wikidata: String? = null,
        fee: String? = null,
        charge: String? = null,
        startDate: String? = null,
        historicType: String? = null,
        colorHex: String? = null,
        showOnMap: Boolean = true
    ) : this(
        place_id = 0,
        display_name = displayName,
        lat = latitude.toString(),
        lon = longitude.toString(),
        type = type,
        category = category,
        placeName = placeName,
        road = road,
        houseNumber = houseNumber,
        suburb = suburb,
        city = city,
        postcode = postcode,
        openingHours = openingHours,
        wheelchair = wheelchair,
        brand = brand,
        operator = operator,
        phone = phone,
        email = email,
        website = website,
        wikipedia = wikipedia,
        wikidata = wikidata,
        fee = fee,
        charge = charge,
        startDate = startDate,
        historicType = historicType,
        colorHex = colorHex,
        showOnMap = showOnMap,
        placeCategory = placeCategory,
        displayName = displayName,
        isLocalStop = isLocalStop,
        stopId = stopId,
        stopType = stopType
    )
}
